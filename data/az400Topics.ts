// Flat list of all topics for search
export const getAllTopics = (): { id: string; label: string; domain: string; domainColor: string; description?: string; keyPoints?: string[] }[] => {
  const topics: { id: string; label: string; domain: string; domainColor: string; description?: string; keyPoints?: string[] }[] = [];
  
  const flatten = (nodes: MindMapNode[], domainLabel: string, domainColor: string) => {
    for (const node of nodes) {
      topics.push({
        id: node.id,
        label: node.label,
        domain: domainLabel,
        domainColor,
        description: node.description,
        keyPoints: node.keyPoints,
      });
      if (node.children) {
        flatten(node.children, domainLabel, domainColor);
      }
    }
  };
  
  for (const domain of AZ400_DOMAINS) {
    topics.push({
      id: domain.id,
      label: domain.label,
      domain: domain.label,
      domainColor: domain.color,
      description: domain.description,
    });
    flatten(domain.children, domain.label, domain.color);
  }
  
  return topics;
};
